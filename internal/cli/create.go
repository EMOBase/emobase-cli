func (a *App) createCmd() *cobra.Command {
	create := &cobra.Command{
		Use:   "create",
		Short: "Generate a stack's .env with that repository's init.sh",
		Long: `create only scaffolds each stack's .env; it does not start containers.
Use emobase up or emobase bootstrap to start the stacks.

It asks for the values the selected stack needs, offering the repository's
defaults. Values passed as flags skip their question; --yes keeps every default
without prompting. Secrets are generated by that repository and stay in its
own .env; the CLI never stores or copies them.`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			if a.Yes {
				return fmt.Errorf("choose a component: emobase create infra|portal|species")
			}
			choice, err := promptChoice(cmd, "Create which component?", []string{"infra", "portal", "species"}, 1)
			if err != nil {
				return err
			}
			var child *cobra.Command
			switch choice {
			case 1:
				child = a.createInfraCmd()
			case 2:
				child = a.createPortalCmd()
			default:
				child = a.createSpeciesCmd()
			}
			return child.RunE(cmd, nil)
		},
	}
	create.AddCommand(a.createInfraCmd(), a.createPortalCmd(), a.createSpeciesCmd())
	return create
}

type infraOpts struct {
	dir, keycloakURL, keycloakPort, network string
	local, force, clone, dryRun             bool
}

func (a *App) createInfraCmd() *cobra.Command {
	o := &infraOpts{}
	cmd := &cobra.Command{
		Use:   "infra",
		Short: "Scaffold emobase-infra/.env",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			root, err := workspace.ResolveRoot(a.WorkspaceFlag)
			if err != nil {
				return err
			}
			if o.dir == "" {
				o.dir = filepath.Join(root, "emobase-infra")
			}
			if o.dir, err = filepath.Abs(o.dir); err != nil {
				return err
			}
			r := &scaffold.Runner{DryRun: o.dryRun, Stdin: cmd.InOrStdin(), Stdout: cmd.OutOrStdout(), Stderr: cmd.ErrOrStderr()}
			if err := a.ensureCheckoutPrompt(cmd, r, o.dir, repoInfra, "", &o.clone); err != nil {
				return err
			}
			if !o.dryRun {
				if _, err := os.Stat(filepath.Join(o.dir, ".env")); err == nil && !o.force {
					return fmt.Errorf("%s/.env already exists; pass --force to regenerate it (this rotates shared secrets)", o.dir)
				}
			}
			initArgs := []string{}
			add := func(flag, value string) {
				if value != "" {
					initArgs = append(initArgs, flag, value)
				}
			}
			if a.Yes {
				initArgs = append(initArgs, "-y")
			}
			if o.local {
				initArgs = append(initArgs, "--local")
			}
			if o.force {
				initArgs = append(initArgs, "--force")
			}
			add("--keycloak-public-url", o.keycloakURL)
			add("--keycloak-host-port", o.keycloakPort)
			add("--infra-network", o.network)
			return r.Init(o.dir, initArgs...)
		},
	}
	f := cmd.Flags()
	f.StringVar(&o.dir, "dir", "", "checkout directory (default: <workspace>/emobase-infra)")
	f.StringVar(&o.keycloakURL, "keycloak-public-url", "", "browser-facing Keycloak base URL, e.g. https://auth.example.org/keycloak")
	f.StringVar(&o.keycloakPort, "keycloak-host-port", "", "host port for Keycloak (default 8081)")
	f.StringVar(&o.network, "infra-network", "", "shared Docker network (default emobase-infra)")
	f.BoolVar(&o.local, "local", false, "local trial: use localhost URLs")
	f.BoolVar(&o.force, "force", false, "overwrite an existing .env (rotates secrets)")
	f.BoolVar(&o.clone, "clone", false, "clone the repository when the directory is missing")
	f.BoolVar(&o.dryRun, "dry-run", false, "print commands without running them")
	return cmd
}

type portalOpts struct {
	dir, publicServer, httpPort, infraDir string
	realm, clientID, clientSecret         string
	local, force, clone, dryRun           bool
}

func (a *App) createPortalCmd() *cobra.Command {
	o := &portalOpts{}
	cmd := &cobra.Command{
		Use:   "portal",
		Short: "Scaffold emobase-portal-deploy/.env",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			root, err := workspace.ResolveRoot(a.WorkspaceFlag)
			if err != nil {
				return err
			}
			if o.dir == "" {
				o.dir = filepath.Join(root, "emobase-portal-deploy")
			}
			if o.infraDir == "" {
				o.infraDir = filepath.Join(root, "emobase-infra")
			}
			if o.dir, err = filepath.Abs(o.dir); err != nil {
				return err
			}
			if o.infraDir, err = filepath.Abs(o.infraDir); err != nil {
				return err
			}
			r := &scaffold.Runner{DryRun: o.dryRun, Stdin: cmd.InOrStdin(), Stdout: cmd.OutOrStdout(), Stderr: cmd.ErrOrStderr()}
			if err := a.ensureCheckoutPrompt(cmd, r, o.dir, repoPortal, "", &o.clone); err != nil {
				return err
			}
			if !o.dryRun {
				if _, err := os.Stat(filepath.Join(o.dir, ".env")); err == nil && !o.force {
					return fmt.Errorf("%s/.env already exists; pass --force to regenerate it", o.dir)
				}
			}
			initArgs := []string{}
			if a.Yes {
				initArgs = append(initArgs, "-y")
			}
			if o.local {
				initArgs = append(initArgs, "--local")
			}
			if o.force {
				initArgs = append(initArgs, "--force")
			}
			if o.publicServer != "" {
				initArgs = append(initArgs, "--public-server", o.publicServer)
			}
			if o.httpPort != "" {
				initArgs = append(initArgs, "--http-port", o.httpPort)
			}
			if o.realm != "" {
				initArgs = append(initArgs, "--keycloak-realm", o.realm)
			}
			if o.clientID != "" {
				initArgs = append(initArgs, "--keycloak-client-id", o.clientID)
			}
			if o.clientSecret != "" {
				initArgs = append(initArgs, "--keycloak-client-secret", o.clientSecret)
			}
			initArgs = append(initArgs, "--infra-dir", o.infraDir)
			if err := r.Init(o.dir, initArgs...); err != nil {
				return err
			}
			if o.dryRun {
				return nil
			}
			ws, err := workspace.Discover(root)
			if err != nil {
				return fmt.Errorf(".env created, but rediscovery failed: %w", err)
			}
			if ws.Portal == nil || ws.Portal.MissingEnv {
				return fmt.Errorf(".env created, but %s was not recognised as a portal checkout", o.dir)
			}
			origin, _ := ws.Portal.Get("PUBLIC_SERVER")
			if origin == "" {
				return fmt.Errorf("%s has no PUBLIC_SERVER", ws.Portal.EnvPath)
			}
			fmt.Fprintln(cmd.OutOrStdout())
			if infraReady(cmd.Context(), ws) {
				fmt.Fprintln(cmd.OutOrStdout(), title("Database"))
				if err := ensurePortalDatabase(r, ws, ws.Portal); err != nil {
					return err
				}
				fmt.Fprintln(cmd.OutOrStdout(), title("Keycloak realm"))
				if err := ensureStackRealm(cmd.Context(), r, ws, ws.Portal); err != nil {
					return err
				}
			} else {
				fmt.Fprintln(cmd.OutOrStdout(), muted("Infra is not running; the portal database and realm will be created by emobase up or emobase bootstrap."))
			}
			fmt.Fprintln(cmd.OutOrStdout(), "Created "+ws.Portal.EnvPath)
			return nil
		},
	}
	f := cmd.Flags()
	f.StringVar(&o.dir, "dir", "", "checkout directory (default: <workspace>/emobase-portal-deploy)")
	f.StringVar(&o.publicServer, "public-server", "", "portal PUBLIC_SERVER")
	f.StringVar(&o.httpPort, "http-port", "", "host port for nginx (default 9080)")
	f.StringVar(&o.realm, "keycloak-realm", "", "portal realm (default emobase-portal)")
	f.StringVar(&o.clientID, "keycloak-client-id", "", "portal client ID (default emobase-portal-client)")
	f.StringVar(&o.clientSecret, "keycloak-client-secret", "", "portal client secret (generated when omitted)")
	f.StringVar(&o.infraDir, "infra-dir", "", "emobase-infra checkout (default: <workspace>/emobase-infra)")
	f.BoolVar(&o.local, "local", false, "local trial: use localhost URLs")
	f.BoolVar(&o.force, "force", false, "overwrite an existing .env")
	f.BoolVar(&o.clone, "clone", false, "clone the repository when the directory is missing")
	f.BoolVar(&o.dryRun, "dry-run", false, "print commands without running them")
	return cmd
}

