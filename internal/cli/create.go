type speciesOpts struct {
	species, dir, publicServer, httpPort, portalServer, portalInternalURL string
	realm, directusDB, containerPrefix, infraDir, portalDir               string
	local, force, clone, apply, dryRun                                    bool
}

func (a *App) createSpeciesCmd() *cobra.Command { return a.newSpeciesAddCmd("species") }

func (a *App) newSpeciesAddCmd(use string) *cobra.Command {
	o := &speciesOpts{}
	cmd := &cobra.Command{
		Use:   use,
		Short: "Scaffold a species checkout (one emobase-deploy clone per species)",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			return a.runSpeciesAdd(cmd, o)
		},
	}
	f := cmd.Flags()
	f.StringVarP(&o.species, "species", "s", "", "4-letter species code, e.g. Tcas (required)")
	f.StringVar(&o.dir, "dir", "", "checkout directory (default: <workspace>/emobase-deploy-<species>)")
	f.StringVar(&o.publicServer, "public-server", "", "species PUBLIC_SERVER")
	f.StringVar(&o.httpPort, "http-port", "", "host port (default 9090)")
	f.StringVar(&o.portalServer, "portal-server", "", "portal URL when there is no local portal checkout")
	f.StringVar(&o.portalInternalURL, "portal-internal-url", "", "portal URL reachable from inside containers")
	f.StringVar(&o.realm, "realm", "", "'shared' or a dedicated realm name (default shared)")
	f.StringVar(&o.directusDB, "directus-db", "", "Directus database (default directus_<species>)")
	f.StringVar(&o.containerPrefix, "container-prefix", "", "Compose project/container prefix (default: species slug)")
	f.StringVar(&o.infraDir, "infra-dir", "", "emobase-infra checkout (default: <workspace>/emobase-infra)")
	f.StringVar(&o.portalDir, "portal-dir", "", "portal checkout (default: <workspace>/emobase-portal-deploy when present)")
	f.BoolVar(&o.local, "local", false, "local trial: use localhost URLs")
	f.BoolVar(&o.force, "force", false, "overwrite an existing .env")
	f.BoolVar(&o.clone, "clone", false, "clone emobase-deploy (branch dev) when the directory is missing")
	f.BoolVar(&o.apply, "apply", false, "after scaffolding, create the database, register the origin, initialise Directus and start the stack")
	f.BoolVar(&o.dryRun, "dry-run", false, "print commands without running them")
	return cmd
}

func (a *App) runSpeciesAdd(cmd *cobra.Command, o *speciesOpts) error {
	root, err := workspace.ResolveRoot(a.WorkspaceFlag)
	if err != nil {
		return err
	}
	if strings.TrimSpace(o.species) == "" {
		return fmt.Errorf("pass --species CODE (for example --species Tcas)")
	}
	slug := speciesSlug(o.species)
	if slug == "" {
		return fmt.Errorf("invalid --species %q", o.species)
	}
	if o.dir == "" {
		o.dir = filepath.Join(root, "emobase-deploy-"+slug)
	}
	if o.infraDir == "" {
		o.infraDir = filepath.Join(root, "emobase-infra")
	}
	if o.portalDir == "" {
		candidate := filepath.Join(root, "emobase-portal-deploy")
		if _, err := os.Stat(filepath.Join(candidate, ".env")); err == nil {
			o.portalDir = candidate
		}
	}
	if o.realm == "" {
		o.realm = "shared"
	}
	if o.httpPort == "" {
		o.httpPort = "9090"
	}
	if o.directusDB == "" {
		o.directusDB = "directus_" + slug
	}
	if o.containerPrefix == "" {
		o.containerPrefix = slug
	}
	if o.dir, err = filepath.Abs(o.dir); err != nil {
		return err
	}
	if o.infraDir, err = filepath.Abs(o.infraDir); err != nil {
		return err
	}
	if o.portalDir != "" {
		if o.portalDir, err = filepath.Abs(o.portalDir); err != nil {
			return err
		}
	}
	r := &scaffold.Runner{DryRun: o.dryRun, Stdout: cmd.OutOrStdout(), Stderr: cmd.ErrOrStderr()}
	if err := ensureCheckout(r, o.dir, repoSpecies, branchDeploy, o.clone); err != nil {
		return err
	}
	if !o.dryRun {
		if _, err := os.Stat(filepath.Join(o.dir, ".env")); err == nil && !o.force {
			return fmt.Errorf("%s/.env already exists; pass --force to regenerate it", o.dir)
		}
		if _, err := os.Stat(filepath.Join(o.infraDir, ".env")); err != nil {
			return fmt.Errorf("%s/.env is missing; run emobase create infra first", o.infraDir)
		}
	}
	if !o.local && o.publicServer == "" {
		return fmt.Errorf("pass --public-server URL or --local")
	}
	if o.portalDir == "" && o.portalServer == "" {
		return fmt.Errorf("pass --portal-server URL or clone emobase-portal-deploy next to this workspace")
	}
	args := []string{"-y", "--species", o.species, "--http-port", o.httpPort, "--infra-dir", o.infraDir,
		"--keycloak-realm", o.realm, "--directus-db", o.directusDB, "--container-prefix", o.containerPrefix}
	if o.local {
		args = append(args, "--local")
	}
	if o.force {
		args = append(args, "--force")
	}
	if o.publicServer != "" {
		args = append(args, "--public-server", o.publicServer)
	}
	if o.portalInternalURL != "" {
		args = append(args, "--portal-internal-url", o.portalInternalURL)
	}
	if o.portalDir != "" {
		args = append(args, "--portal-dir", o.portalDir)
	} else {
		args = append(args, "--portal-server", o.portalServer)
	}
	if err := r.Init(o.dir, args...); err != nil {
		return err
	}
	if o.dryRun {
		if o.apply {
			fmt.Fprintln(cmd.OutOrStdout(), "+ (dry-run) emobase species setup "+o.dir)
		}
		return nil
	}
	ws, err := workspace.Discover(root)
	if err != nil {
		return fmt.Errorf(".env created, but rediscovery failed: %w", err)
	}
	sp := ws.FindSpecies(filepath.Base(o.dir))
	if sp == nil {
		return fmt.Errorf(".env created, but %s was not recognised as a species checkout", o.dir)
	}
	if !o.apply {
		fmt.Fprintln(cmd.OutOrStdout())
		fmt.Fprintln(cmd.OutOrStdout(), "Created "+sp.EnvPath)
		fmt.Fprintln(cmd.OutOrStdout(), "Next: emobase species setup "+filepath.Base(o.dir))
		return nil
	}
	return a.setupSpecies(cmd, ws, sp, &scaffold.Runner{Stdout: cmd.OutOrStdout(), Stderr: cmd.ErrOrStderr()})
}

// setupSpecies performs the documented post-init steps for one species.
func (a *App) setupSpecies(cmd *cobra.Command, ws *workspace.Workspace, sp *workspace.Stack, r *scaffold.Runner) error {
	if ws.Infra == nil {
		return fmt.Errorf("no emobase-infra checkout found; clone it next to this workspace")
	}
	out := cmd.OutOrStdout()
	db, _ := sp.Get("DIRECTUS_DB_DATABASE")
	if db == "" {
		return fmt.Errorf("%s has no DIRECTUS_DB_DATABASE; run emobase doctor --fix first", sp.EnvPath)
	}
	fmt.Fprintln(out, title("Database"))
	if err := r.CreateDatabase(ws.Infra.Dir, db); err != nil {
		return err
	}
	realm, _ := sp.Get("KEYCLOAK_REALM")
	infraRealm, _ := ws.Infra.Get("KEYCLOAK_REALM")
	origin, _ := sp.Get("PUBLIC_SERVER")
	if realm == infraRealm && origin != "" {
		fmt.Fprintln(out, title("Keycloak origin"))
		if err := r.AllowOrigin(ws.Infra.Dir, origin); err != nil {
			return err
		}
	}
	fmt.Fprintln(out, title("Directus"))
	if err := r.SetupDirectus(sp.Dir); err != nil {
		return err
	}
	fmt.Fprintln(out, title("Start"))
	if err := r.Up(sp.Dir); err != nil {
		return err
	}
	fmt.Fprintln(out)
	state := "is running"
	if r.DryRun {
		state = "would be running"
	}
	fmt.Fprintf(out, "%s %s %s at %s\n", ui.OK("OK"), sp.Name, state, origin)
	return nil
}

func ensureCheckout(r *scaffold.Runner, dir, url, branch string, clone bool) error {
	if _, err := os.Stat(filepath.Join(dir, "compose.yml")); err == nil {
		return nil
	}
	if !clone {
		return fmt.Errorf("%s is not an EMOBase checkout\n  clone it with: git clone %s %s\n  or re-run with --clone", dir, url, dir)
	}
	return r.Clone(dir, url, branch)
}

func speciesSlug(s string) string {
	s = strings.ToLower(strings.TrimSpace(s))
	var b strings.Builder
	for _, r := range s {
		if r >= 'a' && r <= 'z' || r >= '0' && r <= '9' {
			b.WriteRune(r)
		}
	}
	return b.String()
}
