func (a *App) runSpeciesAdd(cmd *cobra.Command, o *speciesOpts) error {
	root, err := workspace.ResolveRoot(a.WorkspaceFlag)
	if err != nil {
		return err
	}
	if strings.TrimSpace(o.species) == "" {
		if a.Yes {
			return fmt.Errorf("pass --species CODE (for example --species Tcas)")
		}
		code, err := promptRequired(cmd, "Species code", "Tcas")
		if err != nil {
			return err
		}
		o.species = code
	}
	slug := speciesSlug(o.species)
	if slug == "" {
		return fmt.Errorf("invalid --species %q", o.species)
	}
	if o.dir == "" {
		o.dir = filepath.Join(root, "emobase-deploy-"+slug)
	}
	if o.infraDir == "" {
		o.infraDir = filepath.Join(root, "emobase-infra")
	}
	if o.portalDir == "" {
		candidate := filepath.Join(root, "emobase-portal-deploy")
		if _, err := os.Stat(filepath.Join(candidate, ".env")); err == nil {
			o.portalDir = candidate
		}
	}
	if o.dir, err = filepath.Abs(o.dir); err != nil {
		return err
	}
	if o.infraDir, err = filepath.Abs(o.infraDir); err != nil {
		return err
	}
	if o.portalDir != "" {
		if o.portalDir, err = filepath.Abs(o.portalDir); err != nil {
			return err
		}
	}
	r := &scaffold.Runner{DryRun: o.dryRun, Stdin: cmd.InOrStdin(), Stdout: cmd.OutOrStdout(), Stderr: cmd.ErrOrStderr()}
	if err := a.ensureCheckoutPrompt(cmd, r, o.dir, repoSpecies, branchDeploy, &o.clone); err != nil {
		return err
	}
	if !o.dryRun {
		if _, err := os.Stat(filepath.Join(o.dir, ".env")); err == nil && !o.force {
			return fmt.Errorf("%s/.env already exists; pass --force to regenerate it", o.dir)
		}
		if _, err := os.Stat(filepath.Join(o.infraDir, ".env")); err != nil {
			return fmt.Errorf("%s/.env is missing; run emobase create infra first", o.infraDir)
		}
	}
	args := []string{"--species", o.species, "--infra-dir", o.infraDir}
	add := func(flag, value string) {
		if value != "" {
			args = append(args, flag, value)
		}
	}
	if a.Yes {
		args = append(args, "-y")
	}
	if o.local {
		args = append(args, "--local")
	}
	if o.force {
		args = append(args, "--force")
	}
	add("--public-server", o.publicServer)
	add("--http-port", o.httpPort)
	add("--portal-internal-url", o.portalInternalURL)
	add("--keycloak-realm", o.realm)
	add("--keycloak-client-id", o.clientID)
	add("--keycloak-client-secret", o.clientSecret)
	add("--coco-username", o.cocoUser)
	add("--coco-password", o.cocoPass)
	add("--directus-db", o.directusDB)
	add("--container-prefix", o.containerPrefix)
	if o.portalDir != "" {
		add("--portal-dir", o.portalDir)
	} else {
		add("--portal-server", o.portalServer)
	}
	if err := r.Init(o.dir, args...); err != nil {
		return err
	}
	if o.dryRun {
		if o.apply {
			fmt.Fprintln(cmd.OutOrStdout(), "+ (dry-run) emobase species setup "+o.dir)
		}
		return nil
	}
	ws, err := workspace.Discover(root)
	if err != nil {
		return fmt.Errorf(".env created, but rediscovery failed: %w", err)
	}
	sp := ws.FindSpecies(filepath.Base(o.dir))
	if sp == nil {
		return fmt.Errorf(".env created, but %s was not recognised as a species checkout", o.dir)
	}
	infraUp := infraReady(cmd.Context(), ws)
	if !o.apply && !a.Yes && canPrompt(cmd.InOrStdin()) && infraUp {
		o.apply, err = promptConfirm(cmd, "Set up the species now (database, Keycloak origin, Directus, start)?", false)
		if err != nil {
			return err
		}
	}
	if !o.apply {
		if keycloakRunning(cmd.Context(), ws) {
			fmt.Fprintln(cmd.OutOrStdout(), title("Keycloak realm"))
			if err := ensureStackRealm(cmd.Context(), r, ws, sp); err != nil {
				return err
			}
			fmt.Fprintln(cmd.OutOrStdout())
		} else {
			fmt.Fprintln(cmd.OutOrStdout(), muted("Infra is not running; the species realm and database will be created by emobase species setup or emobase bootstrap."))
		}
		fmt.Fprintln(cmd.OutOrStdout())
		fmt.Fprintln(cmd.OutOrStdout(), "Created "+sp.EnvPath)
		fmt.Fprintln(cmd.OutOrStdout(), "Next: start infra, then run: emobase species setup "+filepath.Base(o.dir))
		return nil
	}
	if !infraUp {
		return fmt.Errorf("infra is not running; start it first with: emobase up --only infra")
	}
	return a.setupSpecies(cmd, ws, sp, &scaffold.Runner{Stdout: cmd.OutOrStdout(), Stderr: cmd.ErrOrStderr()})
}

// setupSpecies performs the documented post-init steps for one species.
func (a *App) setupSpecies(cmd *cobra.Command, ws *workspace.Workspace, sp *workspace.Stack, r *scaffold.Runner) error {
	if ws.Infra == nil {
		return fmt.Errorf("no emobase-infra checkout found; clone it next to this workspace")
	}
	if !r.DryRun && !infraReady(cmd.Context(), ws) {
		return fmt.Errorf("infra is not running; start it first with: emobase up --only infra")
	}
	out := cmd.OutOrStdout()
	db, _ := sp.Get("DIRECTUS_DB_DATABASE")
	if db == "" {
		return fmt.Errorf("%s has no DIRECTUS_DB_DATABASE; run emobase doctor --fix first", sp.EnvPath)
	}
	fmt.Fprintln(out, title("Database"))
	if err := r.CreateDatabase(ws.Infra.Dir, db); err != nil {
		return err
	}
	origin, _ := sp.Get("PUBLIC_SERVER")
	fmt.Fprintln(out, title("Keycloak realm"))
	if err := ensureStackRealm(cmd.Context(), r, ws, sp); err != nil {
		return err
	}
	fmt.Fprintln(out, title("Directus"))
	if err := r.SetupDirectus(sp.Dir); err != nil {
		return err
	}
	fmt.Fprintln(out, title("Start"))
	if err := r.Up(sp.Dir); err != nil {
		return err
	}
	fmt.Fprintln(out)
	state := "is running"
	if r.DryRun {
		state = "would be running"
	}
	fmt.Fprintf(out, "%s %s %s at %s\n", ui.OK("OK"), sp.Name, state, origin)
	return nil
}

// ensureCheckoutPrompt clones a missing checkout after asking, when the user
// is at a terminal. Non-interactive runs still need --clone.
func (a *App) ensureCheckoutPrompt(cmd *cobra.Command, r *scaffold.Runner, dir, url, branch string, clone *bool) error {
	if _, err := os.Stat(filepath.Join(dir, "compose.yml")); err == nil {
		return nil
	}
	if !*clone && !a.Yes && canPrompt(cmd.InOrStdin()) {
		ok, err := promptConfirm(cmd, fmt.Sprintf("%s is not an EMOBase checkout. Clone it from %s?", dir, url), true)
		if err != nil {
			return err
		}
		if !ok {
			return fmt.Errorf("no checkout in %s; clone it or pass --dir", dir)
		}
		*clone = true
	}
	return ensureCheckout(r, dir, url, branch, *clone)
}

func ensureCheckout(r *scaffold.Runner, dir, url, branch string, clone bool) error {
	if _, err := os.Stat(filepath.Join(dir, "compose.yml")); err == nil {
		return nil
	}
	if !clone {
		return fmt.Errorf("%s is not an EMOBase checkout\n  clone it with: git clone %s %s\n  or re-run with --clone", dir, url, dir)
	}
	return r.Clone(dir, url, branch)
}

func speciesSlug(s string) string {
	s = strings.ToLower(strings.TrimSpace(s))
	var b strings.Builder
	for _, r := range s {
		if r >= 'a' && r <= 'z' || r >= '0' && r <= '9' {
			b.WriteRune(r)
		}
	}
	return b.String()
}
